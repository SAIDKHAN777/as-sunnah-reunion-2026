import opentype from 'opentype.js';
import fs from 'fs';

// 1. Load exact Inter Display Black TTF
const fontPath = '/tmp/InterDisplay-Black.ttf';
const buf = fs.readFileSync(fontPath);
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));

const TARGET_HEIGHT = 147;
const TARGET_WIDTH = 100;
const HORIZONTAL_COMPRESSION = 0.68;

const digitData = {};

for (let d = 0; d <= 9; d++) {
  const glyph = font.charToGlyph(String(d));
  const bbox = glyph.getBoundingBox();

  const glyphW = bbox.x2 - bbox.x1;
  const glyphH = bbox.y2 - bbox.y1;

  // Scale Y to fill TARGET_HEIGHT (e.g. 147)
  const scaleY = TARGET_HEIGHT / glyphH;
  // Apply 68% horizontal compression
  const scaleX = scaleY * HORIZONTAL_COMPRESSION;

  const scaledW = glyphW * scaleX;
  const offsetX = (TARGET_WIDTH - scaledW) / 2;

  // Transform commands: Font Y is positive upwards, SVG Y is positive downwards
  const commands = glyph.path.commands;
  let pathStr = '';

  for (const cmd of commands) {
    if (cmd.type === 'M') {
      const x = (offsetX + (cmd.x - bbox.x1) * scaleX).toFixed(2);
      const y = (TARGET_HEIGHT - (cmd.y - bbox.y1) * scaleY).toFixed(2);
      pathStr += `M ${x} ${y} `;
    } else if (cmd.type === 'L') {
      const x = (offsetX + (cmd.x - bbox.x1) * scaleX).toFixed(2);
      const y = (TARGET_HEIGHT - (cmd.y - bbox.y1) * scaleY).toFixed(2);
      pathStr += `L ${x} ${y} `;
    } else if (cmd.type === 'Q') {
      const x1 = (offsetX + (cmd.x1 - bbox.x1) * scaleX).toFixed(2);
      const y1 = (TARGET_HEIGHT - (cmd.y1 - bbox.y1) * scaleY).toFixed(2);
      const x = (offsetX + (cmd.x - bbox.x1) * scaleX).toFixed(2);
      const y = (TARGET_HEIGHT - (cmd.y - bbox.y1) * scaleY).toFixed(2);
      pathStr += `Q ${x1} ${y1} ${x} ${y} `;
    } else if (cmd.type === 'C') {
      const x1 = (offsetX + (cmd.x1 - bbox.x1) * scaleX).toFixed(2);
      const y1 = (TARGET_HEIGHT - (cmd.y1 - bbox.y1) * scaleY).toFixed(2);
      const x2 = (offsetX + (cmd.x2 - bbox.x1) * scaleX).toFixed(2);
      const y2 = (TARGET_HEIGHT - (cmd.y2 - bbox.y1) * scaleY).toFixed(2);
      const x = (offsetX + (cmd.x - bbox.x1) * scaleX).toFixed(2);
      const y = (TARGET_HEIGHT - (cmd.y - bbox.y1) * scaleY).toFixed(2);
      pathStr += `C ${x1} ${y1} ${x2} ${y2} ${x} ${y} `;
    } else if (cmd.type === 'Z') {
      pathStr += 'Z ';
    }
  }

  digitData[d] = {
    digit: d,
    width: TARGET_WIDTH,
    height: TARGET_HEIGHT,
    path: pathStr.trim(),
    ...(d === 6 ? { anchor: { x: 48, y: 102, r: 24 } } : {})
  };
}

// 2. Generate TypeScript file
const tsContent = `/**
 * Generated by scripts/make-digits.mjs
 * Digits 0-9 converted from authentic Inter Display Black horizontally compressed to 68%
 * Target ViewBox: 0 0 ${TARGET_WIDTH} ${TARGET_HEIGHT}
 */

export interface DigitGlyph {
  digit: number;
  width: number;
  height: number;
  path: string;
  anchor?: { x: number; y: number; r: number };
}

export const DIGITS: Record<number, DigitGlyph> = ${JSON.stringify(digitData, null, 2)};
`;

const jsContent = `/**
 * Generated by scripts/make-digits.mjs
 * Digits 0-9 converted from authentic Inter Display Black horizontally compressed to 68%
 * Target ViewBox: 0 0 ${TARGET_WIDTH} ${TARGET_HEIGHT}
 */

export const DIGITS = ${JSON.stringify(digitData, null, 2)};
`;

fs.writeFileSync('/home/saidkhan/Foundetion/src/scripts/digits.ts', tsContent);
fs.writeFileSync('/home/saidkhan/Foundetion/src/scripts/digits.js', jsContent);
console.log('Successfully wrote authentic Inter Display Black digits to src/scripts/digits.ts and src/scripts/digits.js');
